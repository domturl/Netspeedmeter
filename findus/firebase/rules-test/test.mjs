import { initializeTestEnvironment, assertFails, assertSucceeds } from "@firebase/rules-unit-testing";
import { doc, setDoc, getDoc, updateDoc, deleteDoc, collection, getDocs, arrayUnion, arrayRemove, serverTimestamp } from "firebase/firestore";
import fs from "fs";
const env = await initializeTestEnvironment({ projectId: "findus-test", firestore: { rules: fs.readFileSync(new URL("../firestore.rules", import.meta.url),"utf8"), host:"127.0.0.1", port:8085 } });
const db = u => env.authenticatedContext(u).firestore();
const anon = env.unauthenticatedContext().firestore();
const P = "pairs/p1";
let n=0; const t = async (name, p) => { await p; n++; console.log("ok", name); };
await t("A creates pair", assertSucceeds(setDoc(doc(db("A"), P), { members: ["A"], createdAt: serverTimestamp() })));
await t("cannot create pair listing someone else", assertFails(setDoc(doc(db("X"), "pairs/p2"), { members: ["X","A"] })));
await t("unauth cannot read", assertFails(getDoc(doc(anon, P))));
await t("C cannot read before joining", assertFails(getDoc(doc(db("C"), P))));
await t("cannot list pairs", assertFails(getDocs(collection(db("A"), "pairs"))));
await t("A writes own location", assertSucceeds(setDoc(doc(db("A"), P+"/locations/A"), { iv:"x", ct:"y", updatedAt: serverTimestamp() })));
await t("A cannot write plaintext fields", assertFails(setDoc(doc(db("A"), P+"/locations/A"), { iv:"x", ct:"y", lat: 1 })));
await t("C cannot read locations", assertFails(getDoc(doc(db("C"), P+"/locations/A"))));
await t("B joins", assertSucceeds(updateDoc(doc(db("B"), P), { members: arrayUnion("B") })));
await t("C cannot join full pair", assertFails(updateDoc(doc(db("C"), P), { members: arrayUnion("C") })));
await t("B cannot add C", assertFails(updateDoc(doc(db("B"), P), { members: ["A","B","C"] })));
await t("B cannot kick A", assertFails(updateDoc(doc(db("B"), P), { members: ["B"] })));
await t("B reads A location", assertSucceeds(getDoc(doc(db("B"), P+"/locations/A"))));
await t("B cannot overwrite A location", assertFails(setDoc(doc(db("B"), P+"/locations/A"), { iv:"x", ct:"z" })));
await t("C cannot write location into pair", assertFails(setDoc(doc(db("C"), P+"/locations/C"), { iv:"x", ct:"z" })));
await t("C cannot list locations", assertFails(getDocs(collection(db("C"), P+"/locations"))));
await t("B lists locations", assertSucceeds(getDocs(collection(db("B"), P+"/locations"))));
await t("A deletes own location", assertSucceeds(deleteDoc(doc(db("A"), P+"/locations/A"))));
await t("A leaves", assertSucceeds(updateDoc(doc(db("A"), P), { members: arrayRemove("A") })));
await t("A can no longer read", assertFails(getDoc(doc(db("A"), P))));
await t("cannot delete pair", assertFails(deleteDoc(doc(db("B"), P))));
await t("other collections denied", assertFails(setDoc(doc(db("A"), "x/y"), { a:1 })));
console.log(`ALL ${n} PASSED`);
await env.cleanup();
